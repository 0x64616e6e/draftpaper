"""Themes and applying them.

A theme (themes/<name>.toml) names the paper, the ink and the window colours; `apply` turns it, with the
user's config, into everything the desktop reads:

  ~/.cache/draftpaper/theme.json    colours and geometry for the shell (shell.qml reads it live)
  ~/.cache/draftpaper/i3.conf       window colours and gaps, so windows end on the sheet's frame line
  ~/.cache/draftpaper/sheet-<output>.png   the sheet for each connected output, set with xwallpaper (feh)

Geometry: the margin is one width in device pixels on every output (i3's gaps are global), the pattern
is drawn at each output's own pixels-per-millimetre (from xrandr), so a 5 mm dot pitch is 5 mm on each.
"""
import json, re, shutil, subprocess, tomllib
from . import config, paths, render

SHEET_DEFAULTS = {"angle": 54.0, "midpoint": 0.45, "blend": 1.0, "shading": 1.0,
                  "glow_strength": 1.0, "glow_size": 1.0, "pattern_strength": 0.5}
WINDOW_KEYS = ("focused", "focused_inactive", "unfocused", "urgent", "text", "text_inactive", "background")
FALLBACK_MM = 6.2      # about 160 PPI, when xrandr reports no physical size


def run(*cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=False)
    except FileNotFoundError:
        return None


def available():
    names = {}
    for d in reversed(paths.THEMES):           # the user's own themes shadow the shipped ones
        for p in sorted(d.glob("*.toml")) if d.is_dir() else []:
            names[p.stem] = p
    return names


def load(name):
    found = available()
    if name not in found:
        raise SystemExit(f"draftpaper: no theme named {name!r} (draftpaper theme list)")
    with found[name].open("rb") as f:
        t = tomllib.load(f)
    t["name"] = name
    t.setdefault("label", name)
    t["sheet"] = {**SHEET_DEFAULTS, **t.get("sheet", {})}
    if "ink" not in t:
        t["ink"] = "#" + "".join(f"{round(v * 0.7):02X}" for v in render.rgb(t["paper_shade"]))
    t.setdefault("alert", "#E2231A")
    for k in WINDOW_KEYS:
        if k not in t.get("windows", {}):
            raise SystemExit(f"draftpaper: theme {name} lacks windows.{k}")
    return t


def xft_dpi():
    r = run("xrdb", "-query")
    m = re.search(r"Xft\.dpi:\s*(\d+)", r.stdout if r else "")
    return int(m.group(1)) if m else 96


def outputs():
    """[(name, width_px, height_px, px_per_mm)] for the connected outputs, primary first."""
    r = run("xrandr", "--query")
    out = []
    for line in (r.stdout if r and r.returncode == 0 else "").splitlines():
        m = re.match(r"^(\S+) connected (primary )?(\d+)x(\d+)\+\d+\+\d+(?:.*?(\d+)mm x (\d+)mm)?", line)
        if m:
            w, h, wmm = int(m.group(3)), int(m.group(4)), int(m.group(5) or 0)
            out.append((m.group(1), w, h, w / wmm if wmm else FALLBACK_MM, bool(m.group(2))))
    out.sort(key=lambda o: not o[4])
    return [o[:4] for o in out]


def apply(name=None, render_sheets=True):
    cfg = config.load()
    t = load(name or cfg["theme"])
    paths.ensure()
    outs = outputs()
    mm_main = outs[0][3] if outs else FALLBACK_MM
    margin_px = round(cfg["margin"] * mm_main)
    scale = xft_dpi() / 96

    # the shell's view of it
    shell = {
        "name": t["name"], "label": t["label"],
        "paper": t["paper"], "ink": t["ink"], "inkAlpha": t["sheet"]["pattern_strength"], "alert": t["alert"],
        "accent": t["windows"]["focused"],
        "marginPx": margin_px,
        "mm": {n: mm for n, _, _, mm in outs}, "mmDefault": mm_main,
        "title": cfg["title"], "cells": cfg["cell"], "alerts": cfg["alerts"], "commands": cfg["commands"],
        "themes": sorted(available()),
    }
    tmp = paths.THEME_JSON.with_suffix(".tmp")
    tmp.write_text(json.dumps(shell, indent=1))
    tmp.replace(paths.THEME_JSON)

    # i3: windows end on the frame line (the line is 2 px from the margin); i3 scales gaps by Xft.dpi/96,
    # and the shell's 3 px dock strip already holds the top
    w = t["windows"]
    gap = round((margin_px + 1) / scale)
    gap_top = round((margin_px + 1 - 3) / scale)
    paths.I3_CONF.write_text(f"""# generated by `draftpaper apply` ({t['label']}); edit the theme or ~/.config/draftpaper/config.toml
# class                 border  background  text  indicator  child_border
client.focused          {w['focused']} {w['background']} {w['text']} {w['focused']} {w['focused']}
client.focused_inactive {w['focused_inactive']} {w['background']} {w['text_inactive']} {w['focused_inactive']} {w['focused_inactive']}
client.unfocused        {w['unfocused']} {w['background']} {w['text_inactive']} {w['unfocused']} {w['unfocused']}
client.urgent           {w['urgent']} {w['urgent']} {w['background']} {w['urgent']} {w['urgent']}
client.background       {w['background']}
gaps inner 0
gaps outer {gap}
gaps top {gap_top}
smart_gaps off
""")

    if render_sheets:
        args = []
        for out, width, height, mm in outs:
            p = paths.CACHE / f"sheet-{out}.png"
            render.sheet(t, width, height, mm, cfg["margin"] * mm_main / mm, p)
            args += ["--output", out, "--zoom", str(p)]
        if args and shutil.which("xwallpaper"):
            run("xwallpaper", *args)
        elif outs and shutil.which("feh"):
            run("feh", "--no-fehbg", "--bg-fill", *[str(paths.CACHE / f"sheet-{o[0]}.png") for o in outs])
    run("i3-msg", "reload")
    return t
